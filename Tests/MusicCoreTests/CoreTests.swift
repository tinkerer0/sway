import XCTest
@testable import MusicCore

final class CoreTests: XCTestCase {
    let a = Track(id: "aaaaaaaaaaa", title: "첫 곡", artist: "가수")
    let b = Track(id: "bbbbbbbbbbb", title: "둘째 곡", artist: "가수")
    func testRenameAndDuplicateKeepIdentityAndOrder() throws {
        var library = LibrarySnapshot()
        let id = try XCTUnwrap(library.createPlaylist(name: "  산책  "))
        XCTAssertTrue(library.add(a, to: id)); XCTAssertTrue(library.add(b, to: id))
        XCTAssertFalse(library.add(a, to: id))
        XCTAssertTrue(library.renamePlaylist(id: id, name: "퇴근길"))
        XCTAssertFalse(library.renamePlaylist(id: id, name: "  "))
        XCTAssertEqual(library.playlists[0].id, id)
        XCTAssertEqual(library.playlists[0].name, "퇴근길")
        XCTAssertEqual(library.playlists[0].trackIDs, [a.id, b.id])
    }
    func testFileRoundTripAndCorruptionPreserved() throws {
        let dir = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
        defer { try? FileManager.default.removeItem(at: dir) }
        let file = LibraryFile(url: dir.appendingPathComponent("library.json"))
        var library = LibrarySnapshot(); library.save(a); library.record(b)
        try file.write(library)
        XCTAssertEqual(try file.load().savedIDs, [a.id])
        XCTAssertEqual(try file.load().history.first?.trackID, b.id)
        for original in [Data("not-json".utf8), Data("{\"schemaVersion\":99}".utf8)] {
            try original.write(to: file.url)
            XCTAssertThrowsError(try file.write(LibrarySnapshot()))
            XCTAssertEqual(try Data(contentsOf: file.url), original)
        }
    }
    func testNormalQueueStopsAndManualNextIgnoresRepeatOne() {
        var queue = PlaybackQueue(); queue.start([a, b], at: 0)
        queue.repeatMode = .one
        XCTAssertTrue(queue.advance(automatically: true)); XCTAssertEqual(queue.current?.id, a.id)
        XCTAssertTrue(queue.advance()); XCTAssertEqual(queue.current?.id, b.id)
        queue.repeatMode = .off
        XCTAssertFalse(queue.advance(automatically: true)); XCTAssertEqual(queue.current?.id, b.id)
        queue.repeatMode = .all
        XCTAssertTrue(queue.advance()); XCTAssertEqual(queue.current?.id, a.id)
    }
    func testMixDeduplicatesWithoutChangingCurrent() {
        var queue = PlaybackQueue(); queue.start([a], at: 0); queue.repeatMode = .all
        queue.enableMix(seed: a, candidates: [a, b, b])
        XCTAssertEqual(queue.tracks.map(\.id), [a.id, b.id]); XCTAssertEqual(queue.repeatMode, .off)
        queue.appendMix([a, b]); XCTAssertEqual(queue.tracks.count, 2)
        queue.stopMix(); XCTAssertEqual(queue.tracks.map(\.id), [a.id]); XCTAssertNil(queue.mixSeed)
    }
    func testMixAcceptsOnlyCompleteDistributionEvidenceForTheSameVideo() {
        let details: [String: Any] = ["videoId": a.id, "title": "Live Forever", "author": "Artist - Topic",
            "shortDescription": "Provided to YouTube by Label\nSong · Artist\nAuto-generated by YouTube.", "lengthSeconds": "240", "isLiveContent": false]
        func response(_ values: [String: Any], category: String = "Music") -> [String: Any] {
            ["videoDetails": values, "microformat": ["playerMicroformatRenderer": ["category": category]]]
        }
        let accepted = CatalogParser.cleanMixTrack(response(details), candidate: a)
        XCTAssertEqual(accepted?.id, a.id); XCTAssertEqual(accepted?.duration, 240)
        for (key, value) in [("videoId", b.id as Any), ("author", "Fan Official Audio" as Any),
                             ("shortDescription", "Official audio" as Any), ("shortDescription", "Provided to YouTube by Label" as Any),
                             ("isLiveContent", true as Any), ("lengthSeconds", "20" as Any), ("lengthSeconds", "3600" as Any),
                             ("lengthSeconds", "nan" as Any), ("title", "Song (Live at Seoul)" as Any)] {
            var changed = details; changed[key] = value
            XCTAssertNil(CatalogParser.cleanMixTrack(response(changed), candidate: a), key)
        }
        for key in details.keys {
            var missing = details; missing.removeValue(forKey: key)
            XCTAssertNil(CatalogParser.cleanMixTrack(response(missing), candidate: a), key)
        }
        XCTAssertNil(CatalogParser.cleanMixTrack(response(details, category: "Entertainment"), candidate: a))
        XCTAssertNil(CatalogParser.cleanMixTrack([:], candidate: a))
        let edited = Track(id: a.id, title: "Song (SFX edit)", artist: a.artist)
        XCTAssertNil(CatalogParser.cleanMixTrack(response(details), candidate: edited))
    }
    func testMixRejectsNoiseVideoAndEditedVersionsWithoutRejectingOrdinarySongNames() {
        for title in ["Song M/V", "Song [MV]", "Song (Official Music Video)", "Song (Official Video)",
                      "Song (Live)", "Live at Seoul", "Song Live", "Song 라이브", "Song (Remix)",
                      "Song + SFX", "Song (sound effects)", "Song slowed + reverb", "Song sped-up", "Song (8D)",
                      "Song cover", "Song (Karaoke)", "Song Intro", "Song Outro", "Song reaction", "Song 효과음", "Rain Sounds"] {
            XCTAssertTrue(MixPolicy.hasUnwantedVersion(title), title)
        }
        for title in ["Live Forever", "Alive", "River", "Discover", "Through the Night (밤편지)", "Ending Scene (이런 엔딩)"] {
            XCTAssertFalse(MixPolicy.hasUnwantedVersion(title), title)
        }
        // 추천이 비어도 원래 사용자가 고른 곡을 바꾸거나 일반 영상으로 채우지 않는다.
        var queue = PlaybackQueue(); queue.start([a], at: 0); queue.enableMix(seed: a, candidates: [])
        XCTAssertEqual(queue.tracks.map(\.id), [a.id]); XCTAssertFalse(queue.advance())
    }
    func testMixSearchTermDropsVideoMarksAndAddsTopicArtist() {
        let cases: [(String, String, String)] = [
            ("PSY - GANGNAM STYLE(강남스타일) M/V", "officialpsy", "PSY - GANGNAM STYLE(강남스타일)"),
            ("BTS (방탄소년단) 'Dynamite' Official MV", "HYBE LABELS", "BTS (방탄소년단) 'Dynamite'"),
            ("Lady Gaga - Poker Face (Official Music Video)", "Lady Gaga", "Lady Gaga - Poker Face"),
            ("Song [Official Lyric Video] 4K", "Label", "Song"),
            ("Through the Night (밤편지)", "IU - Topic", "Through the Night (밤편지) IU"),
            ("Ending Scene (이런 엔딩)", "아이유 - 주제", "Ending Scene (이런 엔딩) 아이유"),
        ]
        for (title, artist, expected) in cases {
            XCTAssertEqual(CatalogParser.mixSearchTerm(for: Track(id: a.id, title: title, artist: artist)), expected, title)
        }
    }
    func testParserHandlesQuotedBracesAndNestedDuplicates() throws {
        let renderer: [String: Any] = ["videoId": a.id, "title": ["runs": [["text": "문자 } \\\" { 한글"]]],
            "ownerText": ["runs": [["text": "가수"]]], "lengthText": ["simpleText": "1:02:03"]]
        let data = try JSONSerialization.data(withJSONObject: ["contents": [["videoRenderer": renderer], ["videoRenderer": renderer]]])
        let html = "<script>var ytInitialData = \(String(decoding: data, as: UTF8.self));</script>"
        let tracks = CatalogParser.tracks(try CatalogParser.initialData(html), renderer: "videoRenderer")
        XCTAssertEqual(tracks.count, 1); XCTAssertEqual(tracks[0].duration, 3723)
        XCTAssertEqual(tracks[0].artist, "가수"); XCTAssertTrue(tracks[0].title.contains("}"))
        XCTAssertThrowsError(try CatalogParser.initialData("<html>unavailable</html>"))
    }
    func testMusicSearchRequiresSourceEvidenceAndKeepsExactVideoIDs() {
        func video(_ id: String, _ title: String, author: String = "Artist", provided: Bool = true, badge: String? = "BADGE_STYLE_TYPE_VERIFIED_ARTIST") -> [String: Any] {
            var node: [String: Any] = ["videoId": id, "title": ["simpleText": title], "ownerText": ["simpleText": author],
                "detailedMetadataSnippets": [["snippetText": ["runs": [["text": provided ? "Provided to YouTube by Label" : "Fan upload"]]]]]]
            if let badge { node["ownerBadges"] = [["metadataBadgeRenderer": ["style": badge]]] }
            return ["videoRenderer": node]
        }
        let rows = [video("aaaaaaaaaaa", "Song (Live)"), video("bbbbbbbbbbb", "Song"),
                    video("ccccccccccc", "Song", author: "Artist - Topic", badge: nil),
                    video("ddddddddddd", "Song Official Audio", provided: false),
                    video("eeeeeeeeeee", "Song Official Audio", author: "Fan", badge: nil),
                    video("fffffffffff", "Song", author: "Copied description", badge: "BADGE_STYLE_TYPE_VERIFIED"),
                    video("ggggggggggg", "Song Official Music Video"), video("bbbbbbbbbbb", "Song")]
        XCTAssertEqual(CatalogParser.tracks(rows, renderer: "videoRenderer").count, 7)
        XCTAssertEqual(CatalogParser.musicTracks(rows, query: "Artist Song").map(\.id), ["bbbbbbbbbbb", "ccccccccccc", "ddddddddddd", "aaaaaaaaaaa"])
        XCTAssertEqual(CatalogParser.musicTracks(rows, query: "Artist Song Live").first?.id, "aaaaaaaaaaa")
    }
    func testPlaybackSessionRoundTripAndLegacyLibraryMigration() throws {
        var queue = PlaybackQueue(); queue.start([a], at: 0); queue.enableMix(seed: a, candidates: [b]); queue.jump(to: 1)
        var state = LibrarySnapshot(); state.save(a); state.lastTrackID = a.id; state.lastPosition = 12
        state.playbackSession = PlaybackSession(queue: queue, position: 37)
        let data = try JSONEncoder().encode(state)
        let saved = try JSONDecoder().decode(LibrarySnapshot.self, from: data)
        let session = try XCTUnwrap(saved.playbackSession)
        let restored = try XCTUnwrap(PlaybackQueue(restoring: session))
        XCTAssertEqual(restored.current?.id, b.id); XCTAssertEqual(restored.mixSeed?.id, a.id)
        XCTAssertEqual(restored.tracks.map(\.id), [a.id, b.id]); XCTAssertEqual(session.position, 37)
        var legacy = try XCTUnwrap(JSONSerialization.jsonObject(with: data) as? [String: Any])
        legacy.removeValue(forKey: "playbackSession")
        let old = try JSONDecoder().decode(LibrarySnapshot.self, from: JSONSerialization.data(withJSONObject: legacy))
        XCTAssertNil(old.playbackSession); XCTAssertEqual(old.savedIDs, [a.id]); XCTAssertEqual(old.lastPosition, 12)
    }
    func testRestoredQueueRejectsInvalidSelectionAndKeepsNormalRepeat() throws {
        var queue = PlaybackQueue(); queue.start([a, b], at: 1); queue.repeatMode = .all
        var session = PlaybackSession(queue: queue, position: .nan)
        XCTAssertEqual(session.position, 0)
        XCTAssertEqual(PlaybackQueue(restoring: session)?.repeatMode, .all)
        session.index = 2; XCTAssertNil(PlaybackQueue(restoring: session))
        session.index = 0; session.mixSeed = Track(id: "bad", title: "", artist: "")
        XCTAssertNil(PlaybackQueue(restoring: session))
    }

}
